/* ============================================================================
   1. DATABASE & SCHEMA EXPLORATION
   Inspect available objects and column metadata in the Gold layer.
============================================================================ */
USE SQLDataWarehouse;
GO

SELECT TABLE_SCHEMA, TABLE_NAME, TABLE_TYPE
FROM INFORMATION_SCHEMA.TABLES
WHERE TABLE_SCHEMA = 'gold';
GO

SELECT TABLE_NAME, COLUMN_NAME, DATA_TYPE, IS_NULLABLE
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_SCHEMA = 'gold'
ORDER BY TABLE_NAME, ORDINAL_POSITION;
GO

/* ============================================================================
   2. DIMENSIONAL ANALYSIS (Cardinality & Unique Values)
   Explore distinct attributes across customer and product dimensions.
============================================================================ */
-- Customer Demographics
SELECT DISTINCT country FROM gold.dim_customers ORDER BY country;
GO

SELECT DISTINCT marital_status FROM gold.dim_customers;
GO

SELECT DISTINCT gender FROM gold.dim_customers;
GO

-- Product Hierarchy
SELECT DISTINCT 
    category, 
    subcategory, 
    product_line, 
    maintenance 
FROM gold.dim_products
ORDER BY category, subcategory;
GO

/* ============================================================================
   3. DATE EXPLORATION (Boundaries & Lifespans)
   Identify the time span of sales and customer age ranges.
============================================================================ */
-- Order Date Boundaries (First, Last, and Total Months/Years of Sales)
SELECT 
    MIN(order_date) AS first_order_date,
    MAX(order_date) AS last_order_date,
    DATEDIFF(YEAR, MIN(order_date), MAX(order_date)) AS order_range_years,
    DATEDIFF(MONTH, MIN(order_date), MAX(order_date)) AS order_range_months
FROM gold.fact_sales;
GO

-- Customer Age Boundaries (Oldest and Youngest Customers)
SELECT 
    MIN(birthdate) AS oldest_birthdate,
    DATEDIFF(YEAR, MIN(birthdate), GETDATE()) AS oldest_age,
    MAX(birthdate) AS youngest_birthdate,
    DATEDIFF(YEAR, MAX(birthdate), GETDATE()) AS youngest_age
FROM gold.dim_customers;
GO

/* ============================================================================
   4. MEASURES EXPLORATION (Key Business Metrics)
   Calculate high-level KPIs and consolidate them into a single summary report.
============================================================================ */
SELECT 'Total Sales' AS measure_name, SUM(sales_amount) AS measure_value FROM gold.fact_sales
UNION ALL
SELECT 'Total Quantity Sold', SUM(quantity) FROM gold.fact_sales
UNION ALL
SELECT 'Average Selling Price', AVG(price) FROM gold.fact_sales
UNION ALL
SELECT 'Total Number of Orders', COUNT(DISTINCT order_number) FROM gold.fact_sales
UNION ALL
SELECT 'Total Number of Products', COUNT(DISTINCT product_key) FROM gold.dim_products
UNION ALL
SELECT 'Total Number of Customers', COUNT(DISTINCT customer_key) FROM gold.dim_customers
UNION ALL
SELECT 'Total Active Customers (Placed Orders)', COUNT(DISTINCT customer_key) FROM gold.fact_sales;
GO

/* ============================================================================
   5. MAGNITUDE ANALYSIS (Measures Grouped by Dimensions)
   Compare key metrics across different customer and product segments.
============================================================================ */
-- Total Customers by Country
SELECT 
    country, 
    COUNT(customer_key) AS total_customers
FROM gold.dim_customers
GROUP BY country
ORDER BY total_customers DESC;
GO

-- Total Customers by Gender
SELECT 
    gender, 
    COUNT(customer_key) AS total_customers
FROM gold.dim_customers
GROUP BY gender
ORDER BY total_customers DESC;
GO

-- Total Products & Average Cost by Category
SELECT 
    category, 
    COUNT(product_key) AS total_products,
    AVG(cost) AS avg_cost
FROM gold.dim_products
GROUP BY category
ORDER BY total_products DESC;
GO

-- Total Revenue Generated by Category
SELECT 
    p.category, 
    SUM(f.sales_amount) AS total_revenue
FROM gold.fact_sales f
LEFT JOIN gold.dim_products p 
    ON f.product_key = p.product_key
GROUP BY p.category
ORDER BY total_revenue DESC;
GO

-- Total Revenue Generated by Customer
SELECT 
    c.customer_key,
    c.first_name,
    c.last_name,
    SUM(f.sales_amount) AS total_revenue
FROM gold.fact_sales f
LEFT JOIN gold.dim_customers c 
    ON f.customer_key = c.customer_key
GROUP BY c.customer_key, c.first_name, c.last_name
ORDER BY total_revenue DESC;
GO

-- Distribution of Sold Items Across Countries
SELECT 
    c.country, 
    SUM(f.quantity) AS total_sold_items
FROM gold.fact_sales f
LEFT JOIN gold.dim_customers c 
    ON f.customer_key = c.customer_key
GROUP BY c.country
ORDER BY total_sold_items DESC;
GO

/* ============================================================================
   6. RANKING ANALYSIS (Top & Bottom Performers)
   Order dimensions by performance metrics using TOP and Window Functions.
============================================================================ */
-- Top 5 Highest Revenue-Generating Products
SELECT TOP 5
    p.product_name,
    SUM(f.sales_amount) AS total_revenue
FROM gold.fact_sales f
LEFT JOIN gold.dim_products p 
    ON f.product_key = p.product_key
GROUP BY p.product_name
ORDER BY total_revenue DESC;
GO

-- Bottom 5 Worst-Performing Products by Revenue (Using ROW_NUMBER)
SELECT *
FROM (
    SELECT 
        p.product_name,
        SUM(f.sales_amount) AS total_revenue,
        ROW_NUMBER() OVER (ORDER BY SUM(f.sales_amount) ASC) AS rank_products
    FROM gold.fact_sales f
    LEFT JOIN gold.dim_products p 
        ON f.product_key = p.product_key
    GROUP BY p.product_name
) t
WHERE rank_products <= 5;
GO

-- Top 10 Customers by Revenue
SELECT TOP 10
    c.customer_key,
    c.first_name,
    c.last_name,
    SUM(f.sales_amount) AS total_revenue
FROM gold.fact_sales f
LEFT JOIN gold.dim_customers c 
    ON f.customer_key = c.customer_key
GROUP BY c.customer_key, c.first_name, c.last_name
ORDER BY total_revenue DESC;
GO

-- Bottom 3 Customers with the Fewest Orders Placed
SELECT TOP 3
    c.customer_key,
    c.first_name,
    c.last_name,
    COUNT(DISTINCT f.order_number) AS total_orders
FROM gold.fact_sales f
LEFT JOIN gold.dim_customers c 
    ON f.customer_key = c.customer_key
GROUP BY c.customer_key, c.first_name, c.last_name
ORDER BY total_orders ASC;
GO